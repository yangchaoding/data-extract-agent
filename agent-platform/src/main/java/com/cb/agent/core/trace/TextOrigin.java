package com.cb.agent.core.trace;

/**
 * 一段文字是怎么得到的。
 *
 * <p>这关系到结果有多可信。程序核对通过，只说明抽取出来的值和读到的文字一致。
 * 文字是识别出来的时候，它和纸面仍然可能不一致，因为识别可能认错了字。
 * 结果里带上来源，调用方可以对识别来的金额、证件号加强复核。
 */
public enum TextOrigin {
    /** 文件本身就是文字：Excel、Word、txt。 */
    NATIVE,
    /** 从 PDF、OFD 的文字层里读出来的。 */
    TEXT_LAYER,
    /** 识别出来的：扫描件、图片，或者已有的识别结果文件。 */
    OCR
}
