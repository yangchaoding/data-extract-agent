package com.cb.agent.core.trace;

/**
 * 一个出处的位置精确到哪一级。
 *
 * <p>结果里的每个坐标都带着它，调用方才知道这个框有多准。同样是"第 2 页的一个框"，
 * 框住的可能是一个字、一行、一个单元格，也可能是整张表。
 *
 * <p>从细到粗排列。取不到细的就降一级，一直降到只有页码。
 */
public enum Granularity {
    /** 精确到字。文字版 PDF、OFD 的文字层能做到。 */
    CHAR,
    /** 精确到一行文字。 */
    LINE,
    /** 精确到表格的一个单元格。Excel 天然就是这一级。 */
    CELL,
    /** 只到版面块：一段文字、一张表、一个标题。PaddleOCR-VL 的输出是这一级，整张表只有一个框。 */
    BLOCK,
    /** 只知道在哪一页，没有框。识别结果里没有坐标时是这一级。 */
    PAGE
}
